def phase_from_fourier(c, F, d):
    """Compute all target-Fourier matrix blocks from the gate permutation."""
    table = {}
    p, q = F.p, F.q
    for controls in product(range(q), repeat=d):
        # Generate target permutation as a concrete basis action first.
        permutation = [F.add[z][F.prod(controls)] for z in range(q)]
        for y, u in product(range(q), repeat=2):
            phases = [(-F.trace[F.mul[y][permutation[z]]]
                       + F.trace[F.mul[u][z]]) % p for z in range(q)]
            entry = root_sum(p, phases)
            if y != u:
                c.check('A5-upper', entry == (0,) * (p - 1),
                        f'{F.name} d={d}: Fourier block has off-diagonal entry {(y,u)}')
            else:
                possible = [e for e in range(p) if entry == tuple(q * v for v in root_sum(p, [e]))]
                c.check('A5-upper', len(possible) == 1,
                        f'{F.name} d={d}: Fourier diagonal is not a p-th root')
                table[controls + (y,)] = possible[0]
    return table


def span(vectors, p):
    """Exact row basis over F_p; numpy is integer-only."""
    pivots, rows = [], []
    for vector in vectors:
        v = np.array(vector, dtype=np.int64, copy=True) % p
        for pivot, row in zip(pivots, rows):
            if v[pivot]:
                v = (v - v[pivot] * row) % p
        nz = np.flatnonzero(v)
        if len(nz):
            pivot = int(nz[0])
            v = v * pow(int(v[pivot]), -1, p) % p
            where = sum(j < pivot for j in pivots)
            pivots.insert(where, pivot)
            rows.insert(where, v)
    return rows


def translation_indices(F, states):
    indexes = {x: i for i, x in enumerate(states)}
    return np.array([[indexes[tuple(F.add[xj][aj] for xj, aj in zip(x, a))]
                      for x in states] for a in states], dtype=np.int64)


def filtration(F, values, shifts, target_level):
    layers, dimensions = [np.array(values, dtype=np.int64)], []
    for _ in range(target_level + 1):
        layers = span(((v[s] - v) % F.p for v in layers for s in shifts), F.p)
        dimensions.append(len(layers))
    return dimensions, layers


