class GateFailure(Exception):
    def __init__(self, gate, detail):
        self.gate, self.detail = gate, detail
        super().__init__(f'{gate}: {detail}')


class Checks:
    def __init__(self, red=None):
        self.red, self.counts, self.records = red, {}, {}

    def check(self, gate, condition, detail):
        self.counts[gate] = self.counts.get(gate, 0) + 1
        if not condition:
            raise GateFailure(gate, detail)

    def record(self, key, value):
        self.records[key] = value


def embeddings(F):
    return [(F[a], F[b], list(range(F[a].q))) for a, b in
            [('F2', 'F4'), ('F2', 'F8'), ('F2', 'F16'),
             ('F3', 'F9'), ('F4', 'F16')]]


def weyl(F, a, b, x, sign=-1):
    y = F.add[x][a]
    return y, sign * F.trace[F.mul[b][y]] % F.p


def a1(c, Fs):
    for F in Fs.values():
        q, p, A, M, T, S = F.q, F.p, F.add, F.mul, F.trace, F.sigma
        for a in range(1, q):
            c.check('A1-symplectic', any(T[M[a][b]] for b in range(q)),
                    f'{F.name}: degenerate trace pairing at {a}')
            c.check('A1-symplectic', F.power(a, q - 1) == 1,
                    f'{F.name}: table is not a field')
        for a, b, u, v in product(range(q), repeat=4):
            original = (T[M[a][v]] - T[M[u][b]]) % p
            sb, sv = (b, v) if c.red == 'frob-one-label' else (S[b], S[v])
            transformed = (T[M[S[a]][sv]] - T[M[S[u]][sb]]) % p
            c.check('A1-symplectic', transformed == original,
                    f'{F.name}: labels {(a,b,u,v)} give {original}->{transformed}')
        sign = 1 if c.red == 'weyl-positive-sign' else -1
        for a, b, x in product(range(q), repeat=3):
            y, phase = weyl(F, a, b, x, sign)
            sy, sphase = weyl(F, S[a], S[b], S[x], sign)
            c.check('A1-Weyl', (S[y], phase) == (sy, sphase),
                    f'{F.name}: Frobenius basis-action mismatch')
        # Full Weyl label pairs, with both zero and unit input sentinels.
        for a, b, u, v in product(range(q), repeat=4):
            for x in [0, 1]:
                y, ph1 = weyl(F, u, v, x, sign)
                z, ph2 = weyl(F, a, b, y, sign)
                want, ph3 = weyl(F, A[a][u], A[b][v], x, sign)
                actual = (ph1 + ph2) % p
                expected = (ph3 + T[M[a][v]]) % p
                c.check('A1-Weyl', z == want and actual == expected,
                        f'{F.name}: reference cocycle labels {(a,b,u,v,x)} '
                        f'phase {actual} != {expected}')
        c.record(F'A1-{F.name}', {'q': q, 'frobenius': S,
                                'trace': T, 'nondegenerate': True})


def a2(c, Fs):
    for K, E, emb in embeddings(Fs):
        T = relative_trace(K, E, emb)
        kernel = [b for b in range(E.q) if T[b] == 0]
        stabilizers = [b for b in range(E.q)
                       if all(E.trace[E.mul[b][x]] == 0 for x in emb)]
        chosen = emb if c.red == 'code-phase-subfield' and E.name == 'F8' else kernel
        support = [x for x in range(E.q)
                   if all(E.trace[E.mul[b][x]] == 0 for b in chosen)]
        c.check('A2-code', chosen == stabilizers and support == emb,
                f'{K.name}->{E.name}: stabilizers={chosen}, true={stabilizers}; '
                f'support={support}, expected={emb}')
        J = inclusion_matrix(K, E, emb)
        P = J @ J.star()
        c.check('A2-code', J.star() @ J == Mat.eye(K.q) and P @ P == P
                and P.tr() == K.q, f'{E.name}: projector/dimension')
        for x in range(E.q):
            roots = root_sum(E.p, [E.trace[E.mul[b][x]] for b in chosen])
            expected = (len(chosen) if x in emb else 0,) + (0,) * (E.p - 2)
            c.check('A2-code', roots == expected, f'{E.name}: projector phase average at {x}')
        for a, b, y in product(range(K.q), range(E.q), range(K.q)):
            physical = weyl(E, emb[a], b, emb[y])
            ly, lp = weyl(K, a, T[b], y)
            c.check('A2-logical', physical == (emb[ly], lp),
                    f'{K.name}->{E.name}: compressed Weyl action {(a,b,y)}')
        for logical in range(K.q):
            lift = emb[logical] if c.red == 'logical-momentum-inclusion' else T.index(logical)
            for y in range(K.q):
                got = E.trace[E.mul[lift][emb[y]]]
                want = K.trace[K.mul[logical][y]]
                c.check('A2-logical', got == want,
                        f'{K.name}->{E.name}: logical {logical}, lift {lift}, '
                        f'input {y}, phase {got} != {want}')
        for b, u in product(range(E.q), repeat=2):
            same_action = all(E.trace[E.mul[b][x]] == E.trace[E.mul[u][x]] for x in emb)
            c.check('A2-logical', same_action == (T[b] == T[u])
                    == (E.sub(b, u) in kernel), f'{E.name}: momentum quotient')
        c.record(f'A2-{K.name}->{E.name}', {'support': support,
                 'phase_stabilizers': stabilizers, 'trace_fibres':
                 [[b for b in range(E.q) if T[b] == a] for a in range(K.q)]})


def a3(c, Fs):
    for K, E, emb in embeddings(Fs):
        T = relative_trace(K, E, emb)
        if c.red == 'relative-trace-projection' and E.name == 'F4':
            T = [x % 2 for x in range(E.q)]
        for a, x in product(range(K.q), range(E.q)):
            left = E.trace[E.mul[emb[a]][x]]
            right = K.trace[K.mul[a][T[x]]]
            c.check('A3-transfer', left == right,
                    f'{K.name}->{E.name}: trace pairing {(a,x)} gives {left}!={right}')
            c.check('A3-transfer', T[E.mul[emb[a]][x]] == K.mul[a][T[x]],
                    f'{K.name}->{E.name}: relative trace linearity')
        c.check('A3-transfer', set(T) == set(range(K.q)), f'{E.name}: trace not onto')
        for x in range(E.q):
            c.check('A3-transfer', T[E.sigma[x]] == K.sigma[T[x]],
                    f'{E.name}: Frobenius trace equivariance')
        R, r = fibre_matrix(K, E, T)
        norm_square = 1 if c.red == 'trace-fibre-unnormalized' else r
        c.check('A3-normalization', (R.star() @ R).scale(Fraction(1, norm_square)) == Mat.eye(K.q),
                f'{K.name}->{E.name}: fibre denominator square {norm_square}, size {r}')
        for x, a in product(range(E.q), range(K.q)):
            sign = 1 if c.red == 'fourier-positive-kernel' and E.p == 3 else -1
            left = sign * E.trace[E.mul[x][emb[a]]] % E.p
            right = -K.trace[K.mul[T[x]][a]] % K.p
            c.check('A3-Fourier', left == right and E.q == r * K.q,
                    f'{K.name}->{E.name}: Fourier entry {(x,a)} '
                    f'phase {left}!={right}; squared normalizations {E.q},{r*K.q}')
        for x, y in product(range(E.q), repeat=2):
            entries = [(-E.trace[E.mul[x][z]] + E.trace[E.mul[y][z]]) % E.p
                       for z in range(E.q)]
            expected = (E.q if x == y else 0,) + (0,) * (E.p - 2)
            c.check('A3-Fourier', root_sum(E.p, entries) == expected,
                    f'{E.name}: Fourier orthogonality {(x,y)}')
        J = inclusion_matrix(K, E, emb)
        UE = Mat(E.q, E.q, {(E.sigma[x], x): 1 for x in range(E.q)})
        UK = Mat(K.q, K.q, {(K.sigma[x], x): 1 for x in range(K.q)})
        c.check('A3-transfer', UE @ J == J @ UK and UE @ R == R @ UK,
                f'{E.name}: isometry Frobenius covariance')
        for a in range(K.q):
            c.check('A3-transfer', E.trace[emb[a]] ==
                    (E.degree // K.degree * K.trace[a]) % E.p,
                    f'{E.name}: character restriction degree')
    K, L, E = Fs['F2'], Fs['F4'], Fs['F16']
    tLK = relative_trace(K, L, [0, 1])
    tEL = relative_trace(L, E, list(range(4)))
    tEK = relative_trace(K, E, [0, 1])
    c.check('A3-transfer', [tLK[tEL[x]] for x in range(16)] == tEK,
            'F2->F4->F16: trace transitivity')
    R1, r1 = fibre_matrix(K, L, tLK)
    R2, r2 = fibre_matrix(L, E, tEL)
    R3, r3 = fibre_matrix(K, E, tEK)
    c.check('A3-normalization', R2 @ R1 == R3 and r1 * r2 == r3,
            'F2->F4->F16: normalized trace-fibre composition')
    J1, J2, J3 = (inclusion_matrix(K, L, [0, 1]),
                   inclusion_matrix(L, E, list(range(4))), inclusion_matrix(K, E, [0, 1]))
    c.check('A3-transfer', J2 @ J1 == J3, 'F2->F4->F16: inclusion tower')
    orbits, unseen = [], set(range(4))
    while unseen:
        x, orbit = min(unseen), []
        while x not in orbit:
            orbit.append(x)
            unseen.remove(x)
            x = L.sigma[x]
        orbits.append(orbit)
    c.check('A3-transfer', len(orbits) == 3 and len(J1.data) == 2,
            'Frobenius invariant vectors versus subfield support')
    c.record('A3-tower', {'relative_trace_F16_F4': tEL, 'absolute_trace_F16': tEK,
             'fibre_denominator_squares': [r1, r2, r3], 'F4_frobenius_orbits': orbits,
             'character_restriction_F4_F2': [L.trace[x] for x in [0, 1]]})


def gate_map(F, d, red=None):
    states = list(product(range(F.q), repeat=d + 1))
    mapping = {}
    for state in states:
        inc = F.prod(state[:-1])
        if red == 'multiplication-as-addition' and d == 2:
            inc = F.add[state[0]][state[1]]
        mapping[state] = state[:-1] + (F.add[state[-1]][inc],)
    return mapping


def a4(c, Fs):
    for F in Fs.values():
        for d in ([1, 2, 3, 4] if F.q <= 3 else [1, 2, 3] if F.q == 4 else [1, 2]):
            M = gate_map(F, d, c.red)
            c.check('A4-multiplication', len(set(M.values())) == len(M),
                    f'{F.name}, d={d}: gate is not bijective')
            for state, output in M.items():
                inc = F.sub(output[-1], state[-1])
                c.check('A4-multiplication', inc == F.prod(state[:-1]),
                        f'{F.name}, d={d}: input {state}, increment {inc}, '
                        f'product {F.prod(state[:-1])}')
                fs = tuple(F.sigma[x] for x in state)
                c.check('A4-multiplication', M[fs] == tuple(F.sigma[x] for x in output),
                        f'{F.name}, d={d}: Frobenius covariance')
                c.check('A4-multiplication', F.sub(output[-1], F.prod(state[:-1])) == state[-1],
                        f'{F.name}, d={d}: subtraction inverse')
    for K, E, emb in embeddings(Fs):
        for d in [1, 2, 3]:
            MK = gate_map(K, d)
            for state, output in MK.items():
                physical = tuple(emb[x] for x in state)
                got = physical[:-1] + (E.add[physical[-1]][E.prod(physical[:-1])],)
                if c.red == 'embedding-coefficient-swap' and K.name == 'F4':
                    got = tuple((x % 4) * 4 + x // 4 for x in got)
                want = tuple(emb[x] for x in output)
                c.check('A4-embedding', got == want,
                        f'{K.name}->{E.name}, d={d}, state={state}: {got}!={want}')
    c.record('A4-F4->F16', {'embedding': list(range(4)),
             'a_times_a_in_F4': Fs['F4'].mul[2][2],
             'embedded_a_times_a_in_F16': Fs['F16'].mul[2][2],
             'tested_control_counts': [1, 2, 3]})


def a6(c, Fs):
    K, E = Fs['F4'], Fs['F16']
    formula, twice = [], []
    for x in range(16):
        a0, b0 = x % 4, x // 4
        aa, bb = K.mul[a0][a0], K.mul[b0][b0]
        shear = 0 if c.red == 'frobenius-no-shear' else K.mul[2][bb]
        got = K.add[aa][shear] + 4 * bb
        formula.append(got)
        c.check('A6-tower', got == E.mul[x][x],
                f'F16 element (a0,b0)=({a0},{b0}): formula={got}, square={E.mul[x][x]}')
        got2 = E.sigma[E.sigma[x]]
        want2 = K.add[a0][b0] + 4 * b0
        twice.append(got2)
        c.check('A6-tower', got2 == want2, f'F16 sigma^2 shear at {x}')
        c.check('A6-tower', E.power(x, 16) == x, f'F16 sigma^4 at {x}')
    c.check('A6-tower', any(twice[x] != x for x in range(16)), 'F16 exact order is below four')
    orbits, unseen = [], set(range(16))
    while unseen:
        x, orbit = min(unseen), []
        while x not in orbit:
            orbit.append(x)
            unseen.remove(x)
            x = twice[x]
        orbits.append(orbit)
    fixed_labels = [x for x in range(16) if twice[x] == x]
    c.check('A6-tower', len(orbits) == 10 and fixed_labels == list(range(4)),
            f'F16 sigma^2 invariant-vector dimension {len(orbits)}, fixed labels {fixed_labels}')
    c.record('A6-explicit', {'sigma': formula, 'sigma_squared': twice,
                           'order': 4, 'b_squared': E.mul[4][4],
                           'sigma_squared_orbits': orbits, 'fixed_basis_labels': fixed_labels})


def run(red=None):
    c, Fs = Checks(red), fields()
    try:
        for gate, probe in [('A1', a1), ('A2', a2), ('A3', a3), ('A4', a4),
                            ('A5', a5), ('A6', a6), ('A7', a7)]:
            if red is None or MUTATIONS[red].startswith(gate):
                probe(c, Fs)
    except GateFailure as exc:
        return {'status': 'FAIL', 'mutation': red, 'failed_gate': exc.gate,
                'diagnostic': exc.detail, 'counts': c.counts}
    return {'status': 'PASS', 'mutation': red, 'counts': c.counts, 'records': c.records}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--red', choices=MUTATIONS, nargs='?', const='frob-one-label')
    for mutation in MUTATIONS:
        parser.add_argument('--red-' + mutation, dest='red', action='store_const', const=mutation,
                            help='mutate data at ' + MUTATIONS[mutation])
    parser.add_argument('--matrix', action='store_true', help='run all red probes before green')
    args = parser.parse_args()
    if args.matrix:
        results = []
        for mutation, intended in MUTATIONS.items():
            result = run(mutation)
            result['intended_gate'] = intended
            result['intended_failure_observed'] = result['status'] == 'FAIL' and result['failed_gate'] == intended
            results.append(result)
            print(json.dumps(result, sort_keys=True), flush=True)
        green = run()
        print(json.dumps(green, sort_keys=True), flush=True)
        return 0 if all(r['intended_failure_observed'] for r in results) and green['status'] == 'PASS' else 1
    result = run(args.red)
    print(json.dumps(result, sort_keys=True))
    return 0 if result['status'] == 'PASS' else 1


if __name__ == '__main__':
    sys.exit(main())
