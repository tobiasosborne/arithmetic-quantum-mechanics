    H4 = Mat(4, 4, {(y, x): (-1) ** L.trace[L.mul[x][y]]
                   for y, x in product(range(4), repeat=2)})
    H2 = Mat(2, 2, {(y, x): (-1) ** K.trace[K.mul[x][y]]
                   for y, x in product(range(2), repeat=2)})
    fourier4 = H4.scale(Fraction(1, 2))
    _, _, QJ = decoder(K, L, first, 1)
    _, _, QV = decoder(K, L, fibre, fibre_den)
    # Both sides of success equality have denominator sqrt(2).
    c.check('A7-Fourier', fibre.star() @ fourier4 == H2 @ first.star(),
            'Fourier-dual success branch V*F_E differs from F_K J*')
    failure = QJ if c.red == 'fourier-failure-original-code' else QV
    c.check('A7-Fourier', failure @ fourier4 == fourier4 @ QJ,
            'Fourier-dual failure branch Q_V F_E differs from F_E Q_J')
    c.record('A7-Fourier-instrument', {'success_denominator_square': 2,
             'success_and_failure_branch_equalities': True, 'target_dimensions': [2, 4]})
    # Auxiliary reset-completion boundary: distinct outputs, explicit state.
    js = decoder(K, L, first, 1)[0]['s']
    outside, inside = Mat.unit(4, 2, 2), Mat.unit(4, 0, 0)
    local = reset(js, outside).kron(reset(js, inside))
    global_reset = reset(js.tensor(js), outside.kron(inside))
    candidate = global_reset if c.red == 'reset-global-as-local' else local
    expected = Mat.eye(2).scale(Fraction(1, 2)).kron(Mat.unit(2, 0, 0))
    c.check('A7-boundary', candidate == expected and candidate != global_reset,
            'global reset erases the second successful output; it differs from independent local reset')
    c.record('A7-reset-boundary', {'local_diagonal': [str(local.data.get((i,i), 0)) for i in range(4)],
             'global_diagonal': [str(global_reset.data.get((i,i), 0)) for i in range(4)]})

