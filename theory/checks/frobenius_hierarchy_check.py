class Field:
    def __init__(self, name, p, base=None, modulus=None):
        self.name, self.p, self.base = name, p, base
        self.modulus = modulus
        self.degree = 1 if base is None else base.degree * (len(modulus) - 1)
        self.q = p ** self.degree
        self.add = [[self._add(a, b) for b in range(self.q)] for a in range(self.q)]
        self.mul = [[self._mul(a, b) for b in range(self.q)] for a in range(self.q)]
        self.neg = [next(b for b in range(self.q) if self.add[a][b] == 0)
                    for a in range(self.q)]
        self.trace = [self._trace(a) for a in range(self.q)]
        self.sigma = [self.power(a, p) for a in range(self.q)]

    def digits(self, a):
        if self.base is None:
            return [a]
        out = []
        for _ in self.modulus[:-1]:
            out.append(a % self.base.q)
            a //= self.base.q
        return out

    def encode(self, digits):
        return sum(x * self.base.q ** j for j, x in enumerate(digits))

    def _add(self, a, b):
        if self.base is None:
            return (a + b) % self.p
        return self.encode([self.base.add[x][y]
                            for x, y in zip(self.digits(a), self.digits(b))])

    def _mul(self, a, b):
        if self.base is None:
            return a * b % self.p
        k = len(self.modulus) - 1
        B = self.base
        c = [0] * (2 * k - 1)
        for i, x in enumerate(self.digits(a)):
            for j, y in enumerate(self.digits(b)):
                c[i + j] = B.add[c[i + j]][B.mul[x][y]]
        for i in range(2 * k - 2, k - 1, -1):
            for j in range(k):
                c[i - k + j] = B.add[c[i - k + j]][B.neg[B.mul[c[i]][self.modulus[j]]]]
        return self.encode(c[:k])

    def power(self, a, n):
        out = 1
        while n:
            if n & 1:
                out = self.mul[out][a]
            a = self.mul[a][a]
            n //= 2
        return out

    def _trace(self, a):
        out, x = 0, a
        for _ in range(self.degree):
            out = self.add[out][x]
            x = self.power(x, self.p)
        assert out < self.p, (self.name, a, out)
        return out

    def sub(self, a, b):
        return self.add[a][self.neg[b]]

    def prod(self, xs):
        out = 1
        for x in xs:
            out = self.mul[out][x]
        return out


