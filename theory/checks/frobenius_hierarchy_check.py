"""A7: exact rational/scaled-rational Kraus computations with retained types."""
from dataclasses import dataclass
from fractions import Fraction
from itertools import product


@dataclass(frozen=True)
class System:
    names: tuple
    dimension: int

    def tensor(self, other):
        return System(self.names + other.names, self.dimension * other.dimension)


@dataclass
class Kraus:
    source: System
    target: System
    numerator: Mat
    denominator_square: int = 1

    def typed(self):
        return (self.numerator.rows, self.numerator.cols) == (self.target.dimension, self.source.dimension)

    def effect(self):
        return (self.numerator.star() @ self.numerator).scale(Fraction(1, self.denominator_square))

    def apply(self, rho):
        return (self.numerator @ rho @ self.numerator.star()).scale(Fraction(1, self.denominator_square))

    def after(self, first):
        if first.target != self.source or not self.typed() or not first.typed():
            raise ValueError('typed Kraus source/target mismatch')
        return Kraus(first.source, self.target, self.numerator @ first.numerator,
                     self.denominator_square * first.denominator_square)

    def tensor(self, other):
        return Kraus(self.source.tensor(other.source), self.target.tensor(other.target),
                     self.numerator.kron(other.numerator),
                     self.denominator_square * other.denominator_square)


def system(F):
    return System((F.name,), F.q)


def decoder(K, E, S, den):
    P = (S @ S.star()).scale(Fraction(1, den))
    Q = Mat.eye(E.q) - P
    return {'s': Kraus(system(E), system(K), S.star(), den),
            'f': Kraus(system(E), system(E), Q)}, P, Q


def effects(branches, n):
    out = Mat(n, n)
    for k in branches.values():
        out = out + k.effect()
    return out


def pure_state(n, entries):
    column = Mat(n, 1, {(i, 0): v for i, v in entries.items()})
    density = column @ column.star()
    return density.scale(Fraction(1, density.tr()))


def choi_from_matrix_units(k):
    n, m = k.source.dimension, k.target.dimension
    answer = Mat(n * m, n * m)
    for i, j in product(range(n), repeat=2):
        answer = answer + Mat.unit(n, i, j).kron(k.apply(Mat.unit(n, i, j)))
    return answer


def choi_gram(k):
    n, m = k.source.dimension, k.target.dimension
    vector = Mat(n * m, 1, {(i * m + o, 0): value
                           for (o, i), value in k.numerator.data.items()})
    return (vector @ vector.star()).scale(Fraction(1, k.denominator_square))


def reset(k, rho):
    success = k.apply(rho)
    return success + Mat.eye(k.target.dimension).scale(
        Fraction(rho.tr() - success.tr(), k.target.dimension))


