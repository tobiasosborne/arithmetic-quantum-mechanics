def relative_trace(K, E, embedding):
    inverse = {x: a for a, x in enumerate(embedding)}
    out = []
    for x in range(E.q):
        total, y = 0, x
        for _ in range(E.degree // K.degree):
            total = E.add[total][y]
            y = E.power(y, K.q)
        out.append(inverse[total])
    return out


def root_sum(p, exponents):
    """Exact sum of p-th roots in Q[zeta]/(1+...+zeta^(p-1))."""
    counts = [0] * p
    for e in exponents:
        counts[e % p] += 1
    return tuple(c - counts[-1] for c in counts[:-1])


class Mat:
    """Sparse rectangular rational matrix with exact arithmetic."""
    def __init__(self, rows, cols, entries=None):
        self.rows, self.cols = rows, cols
        self.data = {ij: Fraction(v) for ij, v in (entries or {}).items() if v}

    @classmethod
    def eye(cls, n):
        return cls(n, n, {(j, j): 1 for j in range(n)})

    @classmethod
    def unit(cls, n, i, j):
        return cls(n, n, {(i, j): 1})

    def __eq__(self, other):
        return (self.rows, self.cols, self.data) == (other.rows, other.cols, other.data)

    def __add__(self, other):
        assert (self.rows, self.cols) == (other.rows, other.cols)
        data = dict(self.data)
        for ij, v in other.data.items():
            data[ij] = data.get(ij, 0) + v
        return Mat(self.rows, self.cols, data)

    def __sub__(self, other):
        return self + other.scale(-1)

    def scale(self, scalar):
        return Mat(self.rows, self.cols, {ij: v * scalar for ij, v in self.data.items()})

    def __matmul__(self, other):
        if self.cols != other.rows:
            raise ValueError('matrix source/target mismatch')
        right = {}
        for (i, j), v in other.data.items():
            right.setdefault(i, []).append((j, v))
        data = {}
        for (i, k), a in self.data.items():
            for j, b in right.get(k, []):
                data[i, j] = data.get((i, j), 0) + a * b
        return Mat(self.rows, other.cols, data)

    def star(self):
        return Mat(self.cols, self.rows, {(j, i): v for (i, j), v in self.data.items()})

    def kron(self, other):
        return Mat(self.rows * other.rows, self.cols * other.cols,
                   {(i * other.rows + k, j * other.cols + l): a * b
                    for (i, j), a in self.data.items()
                    for (k, l), b in other.data.items()})

    def tr(self):
        assert self.rows == self.cols
        return sum(self.data.get((i, i), 0) for i in range(self.rows))


def inclusion_matrix(K, E, embedding):
    return Mat(E.q, K.q, {(x, a): 1 for a, x in enumerate(embedding)})


def fibre_matrix(K, E, trace):
    """Return numerator R and positive denominator square r: V=R/sqrt(r)."""
    return Mat(E.q, K.q, {(x, trace[x]): 1 for x in range(E.q)}), E.q // K.q


def basis_vectors(p, n):
    return list(product(range(p), repeat=n))

