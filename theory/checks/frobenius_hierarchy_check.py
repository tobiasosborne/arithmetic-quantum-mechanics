"""A5: exact operator tables and derivative-span hierarchy certificates.

No polynomial degree is supplied to the membership algorithm. It receives
only a root-exponent table extracted by Fourier conjugating a permutation.
For diagonal D_f, D_f X(a) D_f* has diagonal quotient
zeta^(f(x+a)-f(x)); Z(b) commutes. If every quotient belongs to C_(k-1),
then every conjugated Pauli does: right Pauli multiplication preserves every
hierarchy level. The filtration below spans ALL translation differences over
F_p at each stage. Its last nonzero layer must be constants; the next zero.
Thus this is a finite recursive upper certificate, not a polynomial fit.

The span optimization is sound for root-valued diagonal operators: sums of
exponent tables multiply diagonal operators, and each successive difference
is linear. It does not assert that unrestricted C_k is a group.
"""
